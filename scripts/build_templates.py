"""Bundle the 9 draft DOCX templates and JSON field contracts into shared/docx-templates-data.mjs."""
import base64
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
templates_dir = root / 'templates'
pairs = []
for json_path in sorted(templates_dir.glob('*/*.tg.json')):
    docx_path = json_path.with_suffix('.docx')
    if not docx_path.is_file():
        raise SystemExit(f'Missing DOCX pair for {json_path}')
    contract = json.loads(json_path.read_text(encoding='utf8'))
    encoded = base64.b64encode(docx_path.read_bytes()).decode('ascii')
    pairs.append({
        'template_id': contract['template_id'],
        'version': contract.get('version', 1),
        'status': contract.get('status', 'draft_unapproved'),
        'publication': contract.get('publication', 'blocked_pending_review'),
        'title_tg': contract['title_tg'],
        'title_ru': contract['title_ru'],
        'template_file': contract['template_file'],
        'primary_role': contract['primary_role'],
        'related_roles': contract.get('related_roles', []),
        'fields': contract['fields'],
        'docx_base64': encoded,
    })

out_path = root / 'shared' / 'docx-templates-data.mjs'
out_path.write_text(
    '// Generated by scripts/build_templates.py from templates/*/*.tg.{json,docx}\n'
    f'export const docxTemplates = {json.dumps(pairs, ensure_ascii=False, separators=(",", ":"))};\n',
    encoding='utf8',
)
print(f'Bundled {len(pairs)} DOCX templates into {out_path.relative_to(root)} ({out_path.stat().st_size} bytes).')
