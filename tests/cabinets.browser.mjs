import {openView,backView,homeView} from './onboarding-fixtures.mjs';
import {pickClass} from './onboarding-fixtures.mjs';
import assert from 'node:assert/strict';
import {test} from 'node:test';
import {chromium} from 'playwright';
const host=process.env.SM_BASE_URL??'http://localhost:4180';

test('three physically separate synthetic workspaces work in Chromium',async()=>{
  const browser=await chromium.launch();
  try {
    const page=await browser.newPage({serviceWorkers:'block'});
    page.setDefaultTimeout(4500);
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(`${host}/cabinets/school/teacher.html?lang=tg`);
    assert.match(new URL(page.url()).pathname,/cabinets\/school\/teacher.html$/);
    assert.equal(await page.locator('#institutionPicker').isVisible(),false);
    for(const [key,value] of Object.entries({first:'Демо',last:'Озмоиш', 'work-1':'Информатика'}))await page.locator(`[data-intake-field=${key}]`).fill(value);
    await page.locator('#saveRoleIntake').click();
    await page.locator('#institutionChoice').selectOption('demo-a');
    await page.locator('#confirmInstitution').click();
    await page.waitForURL(url=>url.pathname.endsWith('/school/teacher.html')&&url.searchParams.get('school')==='demo-a'&&url.searchParams.get('lang')==='tg');
    assert.equal(await page.locator('#teacherDocumentPanel').count(),0);
    assert.equal(await page.locator('#workspaceSchool').textContent(),'МТМУ № 1');
    await page.locator('#instructionLanguage').selectOption('tg');
    await page.getByRole('button',{name:'Сабти профил'}).click();
    assert.match(await page.locator('#teacherProfileStatus').textContent(), /Камаш як синф/);
    await pickClass(page.locator('#teacherProfileClasses'),'8А');
    await pickClass(page.locator('#teacherProfileClasses'),'9Б');
    await page.getByRole('button',{name:'Сабти профил'}).click();
    await homeView(page);
    await page.locator('#smMainModules').waitFor();
    assert.equal(await page.locator('#smMainModules [data-open-phase2]').count(),4);
    await page.locator('#workspaceSettingsToggle').click();await page.getByRole('button',{name:'Тағйири профил'}).click();
    await page.locator('#instructionLanguage').selectOption('ru');
    await page.locator('#teacherProfileClasses li').filter({hasText:'8А'}).getByRole('button',{name:'Хориҷ кардан',exact:true}).click();
    await page.getByRole('button',{name:'Сабти профил'}).click();
    await page.emulateMedia({media:'print'});
    assert.equal(await page.locator('#teacherProfilePanel').isVisible(),false);
    await page.emulateMedia({media:'screen'});
    await page.reload();
    await page.locator('#teacherProfileSummary').waitFor();
    assert.equal(await page.locator('#profileClasses').textContent(),'9Б · Технологияи иттилоотӣ');
    assert.equal(await page.locator('#profileInstruction').textContent(),'Русӣ');
    await page.goto(`${host}/cabinets/school/teacher.html?school=demo-b&lang=tg`);
    await page.locator('#teacherProfile').waitFor();
    assert.equal(await page.locator('#workspaceSchool').textContent(),'МТМУ № 4');
    assert.equal(await page.locator('#teacherProfile').isVisible(),true);
    const keys=await page.evaluate(()=>Object.keys(sessionStorage));
    assert.deepEqual(keys,['smartmaktab.demo.teacher.v1.demo-a']);
    await page.goto(`${host}/cabinets/maorif/clerk.html?lang=tg`);
    assert.match(new URL(page.url()).pathname,/cabinets\/maorif\/clerk\.html/);
    await page.getByRole('heading',{name:'Коргаргузори маориф',exact:true}).waitFor();
    await page.goto(`${host}/cabinets/raesat/head.html?lang=tg`);
    await homeView(page);
    await page.getByRole('heading',{name:'Сардори раёсат',exact:true}).waitFor();
    assert.match(new URL(page.url()).pathname,/cabinets\/raesat\/head\.html/);
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    assert.equal(await page.locator('#cabinetLang').count(),0);
    await homeView(page);await openView(page,'raesatCoverage');await page.getByRole('heading',{name:'Пуррагии маълумот'}).waitFor();
    assert.deepEqual(errors,[]);
    assert.equal((await page.request.get(`${host}/dev/supabase-config.json`)).status(),404);
  } finally {await browser.close();}
});
