import {openView,backView,homeView} from './onboarding-fixtures.mjs';
import assert from 'node:assert/strict';
import {test} from 'node:test';
import {chromium} from 'playwright';
const base=process.env.SM_BASE_URL??'http://localhost:4180';
test('Chromium: director profile, school-year validation and printable plan',async()=>{
  const browser=await chromium.launch();
  try{
    const page=await browser.newPage({serviceWorkers:'block',viewport:{width:390,height:844}});
    page.setDefaultTimeout(5500);
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.goto(`${base}/cabinets/school/director.html?school=demo-a&lang=tg`);
    await page.locator('#directorPlanPanel').waitFor({state:'hidden'});
    for(const [id,value] of Object.entries({directorFirst:'Демо',directorLast:'Намуна',directorMiddle:'Шартӣ',directorBirth:'1980',directorEduYears:'12',directorLeadYears:'13',
      directorUniversity:'Донишгоҳи шартӣ',directorSpecialty:'Педагогика',directorAttestation:'2024',directorPhone:'+000 123 45 67',directorEmail:'director@example.test',directorAddress:'Кӯчаи Намуна, 1',directorAwardNotes:'Мукофоти шартӣ, 2024'}))await page.locator(`#${id}`).fill(value);
    await page.locator('#directorGender').selectOption('female');
    await page.locator('#directorAchievements input[value=excellence]').check();
    await page.locator('#directorAchievements input[value=certificate]').check();
    await page.locator('#directorAchievements input[value=monetary]').check();
    await page.locator('#directorDiploma').selectOption('master');
    await page.locator('#directorCategory').selectOption('first');
    await page.locator('#directorLanguages input[value="fa"]').check();
    await page.locator('#directorLanguages input[value="de"]').check();
    await page.locator('#directorLanguages input[value="other"]').check();
    await page.locator('#directorOtherLanguage').fill('Итолиёвӣ');
    await page.locator('#directorPersonnelSave').click();
    assert.match(await page.locator('#directorPersonnelStatus').textContent(),/набояд аз собиқаи маориф зиёд/);
    await page.locator('#directorLeadYears').fill('5');
    await page.locator('#directorPersonnelSave').click();
    await page.locator('#directorPersonnelSummary').waitFor();
    const personal=await page.locator('#directorPersonnelValues').textContent();
    assert.match(personal,/Форсӣ, Олмонӣ, Итолиёвӣ/);
    assert.match(personal,/Зан/);assert.match(personal,/director@example.test/);assert.match(personal,/Аълочии маориф/);
    async function addCourse(title,start,end,state){
      await page.locator('#directorCourseTitle').fill(title);
      await page.locator('#directorCourseProvider').fill('Ташкилоти шартӣ');
      await page.locator('#directorCourseStart').fill(start);
      await page.locator('#directorCourseEnd').fill(end);
      await page.locator('#directorCourseCompletion').selectOption(state);
      await page.locator('#directorAddCourse').click();
    }
    await addCourse('Курси анҷомёфта','2024-02-01','2024-02-29','completed');
    assert.equal(await page.locator('#directorDueNext').textContent(),'28.02.2027');
    await addCourse('Курси дигар','2025-02-01','2025-01-01','completed');
    assert.match(await page.locator('#directorCourseStatus').textContent(),/пеш аз оғоз/);
    await addCourse('Курси ба нақша гирифта','2028-01-10','2028-01-20','planned');
    assert.equal(await page.locator('#directorDueNext').textContent(),'28.02.2027');
    assert.equal(await page.locator('#directorCourseList li').count(),2);
    assert.deepEqual(await page.evaluate(()=>Object.keys(sessionStorage)),[]);

    await page.locator('#directorType').selectOption('gymnasium');
    await page.locator('#directorShifts').selectOption('two');
    await page.getByRole('button',{name:'Сабти профил'}).click();
    await page.locator('#directorYear').fill('2026');
    await page.locator('#directorGoal').fill('Беҳтар кардани кори китобхонаи мактаб.');
    await page.locator('#directorDirection').selectOption('learning');
    await page.locator('#directorOwner').selectOption('academic');
    await page.locator('#directorTitle').fill('<strong>Намоишгоҳ</strong>');
    await page.locator('#directorDue').fill('2026-08');
    await page.locator('#directorAdd').click();
    assert.match(await page.locator('#directorStatus').textContent(),/ба соли таҳсил дохил/);
    await page.locator('#directorDue').fill('2027-01');
    await page.locator('#directorAdd').click();
    await page.locator('#directorTitle').fill('Омода кардани рӯйхати мавзӯъҳо');
    await page.locator('#directorDue').fill('2026-09');
    await page.locator('#directorAdd').click();
    await page.locator('#directorGenerate').click();
    assert.match(await page.locator('#directorSheetSchool').textContent(),/demo-a.*Гимназия/);
    assert.equal(await page.locator('#directorSheetYear').textContent(),'2026–2027');
    assert.deepEqual(await page.locator('#directorSheetTasks li > strong').allTextContents(),['Омода кардани рӯйхати мавзӯъҳо','<strong>Намоишгоҳ</strong>']);
    assert.equal(await page.locator('#directorSheetTasks strong strong').count(),0);
    await backView(page);await page.locator('#directorYear').fill('2027');
    assert.equal(await page.locator('#directorTasks .warn').count(),2);
    await page.locator('#directorGenerate').click();
    assert.match(await page.locator('#directorStatus').textContent(),/муҳлати ҳамаи вазифаҳоро/);
    assert.equal(await page.locator('#directorSheetYear').textContent(),'2026–2027');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    assert.match(await page.locator('#directorSheetShifts').textContent(),/Ду баст/);
    await page.emulateMedia({media:'print'});
    assert.equal(await page.locator('#directorSheet').isVisible(),true);
    assert.equal(await page.locator('#directorProfilePanel').isVisible(),false);
    assert.equal(await page.locator('#directorPersonnel').isVisible(),false);
    assert.doesNotMatch(await page.locator('#directorSheet').innerText(),/Донишгоҳи шартӣ|Намуна|director@example\.test|Курси анҷомёфта/);
    await page.emulateMedia({media:'screen'});
    await page.reload();await page.locator('#directorSummary').waitFor();
    assert.equal(await page.locator('#directorSummaryType').textContent(),'Гимназия');
    assert.equal(await page.locator('#directorSheet').isVisible(),false);
    await page.goto(`${base}/cabinets/school/director.html?school=demo-b&lang=tg`);
    await page.locator('#directorPlanPanel').waitFor({state:'hidden'});
    assert.equal(await page.locator('#directorType').inputValue(),'');
    assert.deepEqual(errors,[]);
  }finally{await browser.close();}
});
