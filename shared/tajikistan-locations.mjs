export function flattenTerritorySeedRows() {
  const rows = [];
  for (const [region_name, districts] of Object.entries(TAJIKISTAN_TERRITORY_TREE)) {
    for (const [district_name, jamoats] of Object.entries(districts)) {
      for (const [jamoat_name, villages] of Object.entries(jamoats)) {
        if (!villages.length) {
          rows.push({ region_name, district_name, jamoat_name, village_name: '' });
        } else {
          for (const village_name of villages) {
            rows.push({ region_name, district_name, jamoat_name, village_name });
          }
        }
      }
    }
  }
  return rows;
}
